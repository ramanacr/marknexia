// Oracle generator for ColorCode 2.0.15 highlighting parity (gate G1).
//
// Usage: dotnet run --project <this folder> -- <repository-root> <source-revision>
//
// It runs the unmodified .NET ColorCodeSyntaxHighlighter (src/Marknexia.Syntax)
// and ColorCode.Core/HTML 2.0.15, and writes three files:
//
//   crates/marknexia-rendering/src/highlight/languages.rs  every ColorCode
//       language in LanguageRepository order: id, CSS class, aliases, the
//       compiled regex pattern (LanguageCompiler output, exactly as .NET
//       builds it), the compiled capture-to-scope list, the group count, and
//       the default StyleDictionary scope-to-class map.
//   crates/marknexia-rendering/src/highlight/unicode.rs   the .NET regex
//       classes \w, \d, \s, the \b word set, and the RegexOptions.IgnoreCase
//       equivalences, measured on every UTF-16 code unit.
//   crates/marknexia-rendering/tests/oracle/highlight.v1.json  HighlightCode
//       output for the corpus (tests/highlight_oracle.rs).
//
// Nothing here is shipped. The .NET sources are referenced, not modified.

using System.Globalization;
using System.Reflection.Metadata;
using System.Reflection.Metadata.Ecma335;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using ColorCode;
using ColorCode.Compilation;
using ColorCode.Styling;
using Marknexia.Syntax;

// A case that .NET cannot finish in this time is recorded as "timeout"
// instead of an output (ColorCode builds its Regex objects without a
// timeout, so this default applies to them).
AppContext.SetData("REGEX_DEFAULT_MATCH_TIMEOUT", TimeSpan.FromSeconds(20));
if (args.Length != 2) throw new ArgumentException("usage: <repository-root> <source-revision>");
string root = Path.GetFullPath(args[0]);
if (!File.Exists(Path.Combine(root, "Cargo.toml"))) throw new InvalidOperationException($"not the repository root: {root}");
string highlightDir = Path.Combine(root, "crates", "marknexia-rendering", "src", "highlight");
Directory.CreateDirectory(highlightDir);

const string Header = "// @generated by crates/marknexia-rendering/tests/oracle/HighlightOracle from\n// ColorCode.Core 2.0.15 on .NET {0}. Do not edit; regenerate instead.\n\n";
string dotnet = Environment.Version.ToString();

WriteLanguages(Path.Combine(highlightDir, "languages.rs"));
WriteUnicode(Path.Combine(highlightDir, "unicode.rs"));
WriteCorpus(Path.Combine(root, "crates", "marknexia-rendering", "tests", "oracle", "highlight.v1.json"), args[1]);
return;

static string RustStr(string text)
{
    var sb = new StringBuilder("\"");
    foreach (char c in text)
    {
        switch (c)
        {
            case '\\': sb.Append("\\\\"); break;
            case '"': sb.Append("\\\""); break;
            case '\r': sb.Append("\\r"); break;
            case '\n': sb.Append("\\n"); break;
            case '\t': sb.Append("\\t"); break;
            default:
                if (char.IsSurrogate(c)) throw new InvalidOperationException("surrogate in pattern");
                if (c < 0x20 || c > 0x7E) sb.Append($"\\u{{{(int)c:x4}}}"); else sb.Append(c);
                break;
        }
    }
    return sb.Append('"').ToString();
}

void WriteLanguages(string path)
{
    // Alias candidates: every string literal in ColorCode.Core plus each
    // language's id, name and CSS class, in several casings. HasAlias is a
    // switch on string literals, so this finds every alias it accepts.
    var asm = typeof(Languages).Assembly;
    var candidates = new SortedSet<string>(StringComparer.Ordinal);
    using (var pe = new PEReader(File.OpenRead(asm.Location)))
    {
        var md = pe.GetMetadataReader();
        var handle = MetadataTokens.UserStringHandle(1);
        while (!handle.IsNil)
        {
            string s = md.GetUserString(handle);
            if (s.Length is > 0 and < 48)
            {
                candidates.Add(s);
                candidates.Add(s.ToLowerInvariant());
                candidates.Add(s.ToUpperInvariant());
            }
            handle = md.GetNextHandle(handle);
        }
    }
    foreach (var l in Languages.All)
    {
        foreach (var s in new[] { l.Id, l.Name, l.CssClassName })
        {
            candidates.Add(s);
            candidates.Add(s.ToLowerInvariant());
            candidates.Add(s.ToUpperInvariant());
        }
    }

    var compiler = new LanguageCompiler(new Dictionary<string, CompiledLanguage>(), new ReaderWriterLockSlim());
    var sb = new StringBuilder(string.Format(Header, dotnet));
    sb.Append("//! ColorCode 2.0.15 language table, in `LanguageRepository` order (the\n");
    sb.Append("//! order `FindById` searches).\n\n");
    sb.Append("use super::{LanguageDef, StyleDef};\n\n");
    sb.Append("pub(super) static LANGUAGES: &[LanguageDef] = &[\n");
    foreach (var l in Languages.All)
    {
        CompiledLanguage compiled = compiler.Compile(l);
        int[] numbers = compiled.Regex.GetGroupNumbers();
        for (int i = 0; i < numbers.Length; i++)
        {
            if (numbers[i] != i) throw new InvalidOperationException($"{l.Id}: group numbers are not contiguous");
        }
        // HasAlias is case-insensitive; the table keeps the lower-case forms.
        var aliases = candidates.Where(l.HasAlias).Select(a => a.ToLowerInvariant()).Distinct().OrderBy(a => a, StringComparer.Ordinal).ToList();
        foreach (var alias in aliases)
        {
            if (!l.HasAlias(alias) || !l.HasAlias(alias.ToUpperInvariant())) throw new InvalidOperationException($"{l.Id}: alias {alias} is case-sensitive");
        }
        sb.Append("    LanguageDef {\n");
        sb.Append($"        id: {RustStr(l.Id)},\n");
        sb.Append($"        css: {RustStr(l.CssClassName)},\n");
        sb.Append($"        aliases: &[{string.Join(", ", aliases.Select(RustStr))}],\n");
        sb.Append($"        pattern: {RustStr(compiled.Regex.ToString())},\n");
        sb.Append($"        captures: &[{string.Join(", ", compiled.Captures.Select(c => c == null ? "None" : $"Some({RustStr(c)})"))}],\n");
        sb.Append($"        groups: {numbers.Length},\n");
        sb.Append("    },\n");
    }
    sb.Append("];\n\n");
    sb.Append("/// `StyleDictionary.DefaultLight`: scope name to CSS class (`ReferenceName`).\n");
    sb.Append("pub(super) static STYLES: &[StyleDef] = &[\n");
    foreach (Style s in StyleDictionary.DefaultLight)
    {
        sb.Append($"    StyleDef {{\n        scope: {RustStr(s.ScopeName)},\n        class: {RustStr(s.ReferenceName)},\n    }},\n");
    }
    sb.Append("];\n");
    File.WriteAllText(path, sb.ToString().Replace("\r\n", "\n"));
    Console.WriteLine($"wrote {path}");
}

void WriteUnicode(string path)
{
    var word = new Regex(@"^\w$");
    var digit = new Regex(@"^\d$");
    var space = new Regex(@"^\s$");
    // `^a\B` matches "a" + c exactly when c is a \b word character.
    var boundaryWord = new Regex(@"^a\B");
    bool[] w = new bool[65536], d = new bool[65536], s = new bool[65536], b = new bool[65536];
    for (int c = 0; c < 65536; c++)
    {
        string one = ((char)c).ToString();
        w[c] = word.IsMatch(one);
        d[c] = digit.IsMatch(one);
        s[c] = space.IsMatch(one);
        b[c] = boundaryWord.IsMatch("a" + one);
    }

    // IgnoreCase equivalences. Candidates are the closure of the invariant
    // and current-culture upper/lower mappings; each member is then checked
    // with an IgnoreCase regex, so the table holds exactly what .NET matches.
    var parent = Enumerable.Range(0, 65536).ToArray();
    int Find(int x) { while (parent[x] != x) x = parent[x] = parent[parent[x]]; return x; }
    void Union(int x, int y) { x = Find(x); y = Find(y); if (x != y) parent[Math.Max(x, y)] = Math.Min(x, y); }
    var culture = CultureInfo.CurrentCulture;
    for (int c = 0; c < 65536; c++)
    {
        char ch = (char)c;
        if (char.IsSurrogate(ch)) continue;
        Union(c, char.ToUpperInvariant(ch));
        Union(c, char.ToLowerInvariant(ch));
        Union(c, char.ToUpper(ch, culture));
        Union(c, char.ToLower(ch, culture));
    }
    var groups = Enumerable.Range(0, 65536).GroupBy(Find).Where(g => g.Count() > 1).ToList();
    var equivalents = new SortedDictionary<int, List<int>>();
    foreach (var group in groups)
    {
        foreach (int c in group)
        {
            var re = new Regex(Regex.Escape(((char)c).ToString()), RegexOptions.IgnoreCase);
            var set = group.Where(x => re.IsMatch(((char)x).ToString())).OrderBy(x => x).ToList();
            if (set.Count > 1) equivalents[c] = set;
        }
    }
    // Every ASCII letter is also checked against the whole BMP, so no
    // equivalence outside the candidate closure can hide for them.
    for (int c = 'A'; c <= 'z'; c++)
    {
        if (!char.IsAsciiLetter((char)c)) continue;
        var re = new Regex(Regex.Escape(((char)c).ToString()), RegexOptions.IgnoreCase);
        var all = Enumerable.Range(0, 65536).Where(x => re.IsMatch(((char)x).ToString())).ToList();
        if (!all.SequenceEqual(equivalents.GetValueOrDefault(c, new List<int> { c }))) throw new InvalidOperationException($"equivalence outside the closure for {(char)c}");
    }

    static string Ranges(bool[] set)
    {
        var sb = new StringBuilder("&[");
        for (int c = 0; c < 65536; c++)
        {
            if (!set[c]) continue;
            int start = c;
            while (c + 1 < 65536 && set[c + 1]) c++;
            sb.Append($"\n    (0x{start:x4}, 0x{c:x4}),");
        }
        return sb.Append("\n]").ToString();
    }

    var sb = new StringBuilder(string.Format(Header, dotnet));
    sb.Append("//! .NET regex character data, measured on every UTF-16 code unit\n");
    sb.Append($"//! (culture `{culture.Name}`).\n\n");
    sb.Append("/// `\\w`: inclusive code-unit ranges.\n");
    sb.Append($"pub(super) static WORD: &[(u16, u16)] = {Ranges(w)};\n\n");
    sb.Append("/// `\\d`.\n");
    sb.Append($"pub(super) static DIGIT: &[(u16, u16)] = {Ranges(d)};\n\n");
    sb.Append("/// `\\s`.\n");
    sb.Append($"pub(super) static SPACE: &[(u16, u16)] = {Ranges(s)};\n\n");
    sb.Append("/// Characters that count as word characters for `\\b` and `\\B`.\n");
    sb.Append($"pub(super) static BOUNDARY_WORD: &[(u16, u16)] = {Ranges(b)};\n\n");
    sb.Append("/// `RegexOptions.IgnoreCase`: for each pattern character with other\n");
    sb.Append("/// equivalents, every input character it matches (itself included).\n");
    sb.Append("pub(super) static CASE_EQUIVALENTS: &[(u16, &[u16])] = &[\n");
    foreach (var (c, set) in equivalents)
    {
        sb.Append($"    (0x{c:x4}, &[{string.Join(", ", set.Select(x => $"0x{x:x4}"))}]),\n");
    }
    sb.Append("];\n");
    File.WriteAllText(path, sb.ToString().Replace("\r\n", "\n"));
    Console.WriteLine($"wrote {path} ({equivalents.Count} case entries)");
}

void WriteCorpus(string path, string revision)
{
    var highlighter = new ColorCodeSyntaxHighlighter();
    var cases = new List<(string Name, string Language, string Code)>();
    void Add(string name, string language, string code) => cases.Add((name, language, code));

    string[] ids = Languages.All.Select(l => l.Id).ToArray();

    // 1. Generic inputs for every language.
    var generic = new (string Name, string Code)[]
    {
        ("empty", ""),
        ("words", "plain words only\n"),
        ("mixed", "x = \"a\\\"b\" + 'c' // d\n/* e */ # f\n-- g\n<tag attr=\"v\">&amp;</tag>\n"),
        ("unterminated", "\"abc\n'def\n/* ghi\n<!-- jkl\n{- x\n@\"m\n(* n\n"),
        ("crlf", "line1\r\nline2 // c\r\n\r\n#x\r\n'q' \"r\"\r\n"),
        ("numbers", "0 1 12 3.14 1e10 1e-5 0x1F 0XAB 1_000 .5 5. 42L 3f 0b101\n"),
        ("unicode", "é ü × ñ — “q” 𝑥 😀 \u200d ſ \u212a İ ı ß Σσς\n\"é\" 'ü' // ñ\n"),
        ("whitespace", "\t  \n\n   \t\n"),
        ("no-final-newline", "if x then y else z"),
    };
    foreach (string id in ids)
    {
        foreach (var (name, code) in generic) Add($"{id}/generic-{name}", id, code);
    }

    // 2. Language samples.
    foreach (var (id, name, code) in Samples.All) Add($"{id}/{name}", id, code);

    // 3. Deterministic token soups over a pool of every language's syntax.
    var random = new Random(20261106);
    foreach (string id in ids)
    {
        for (int n = 0; n < 6; n++)
        {
            var sb = new StringBuilder();
            int length = 40 + random.Next(60);
            for (int t = 0; t < length; t++)
            {
                sb.Append(Samples.Tokens[random.Next(Samples.Tokens.Length)]);
                if (random.Next(4) == 0) sb.Append(' ');
            }
            Add($"{id}/soup-{n}", id, sb.ToString());
        }
    }

    // 4. Language resolution (ResolveLanguage and FindById).
    string resolveCode = "var x = 1; // c\n<b>\"s\"</b>\n";
    foreach (string language in new[]
    {
        "C#", " cs ", "CSharp", "cake", "c", "C++", "cpp", "js", "JS", "javascript", "ts", "TypeScript", "md", "MARKDOWN",
        "ps1", "posh", "pwsh", "powershell", "py", "Python", "vb", "vbnet", "visualbasic", "xaml", "axml", "xml",
        "php", "php5", "kk", "kki", "hs", "fs", "f#", "fsharp", "m", "mat", "matlab", "htm", "html", "aspx", "aspx-cs",
        "aspx-vb", "aspx(c#)", "aspx(vb.net)", "asax", "ashx", "json", "sql", "css", "java", "fortran", "koka",
        "haskell", "unknown", "", "   ", "mermaid", "text", "plaintext", "C#\t", "\nsql\n", "vb.net",
    })
    {
        Add($"resolve/{Escape(language)}", language, resolveCode);
    }

    // 5. Moderate pathological shapes that .NET still finishes.
    foreach (string id in ids)
    {
        Add($"{id}/long-unterminated-quotes", id, "\"" + new string('x', 3000) + "\n" + string.Concat(Enumerable.Repeat("'a", 300)));
        Add($"{id}/long-line", id, string.Concat(Enumerable.Repeat("abc = def(1, \"two\") + ghi; ", 200)) + "\n");
    }

    var output = new JsonArray();
    foreach (var (name, language, code) in cases)
    {
        var entry = new JsonObject { ["name"] = name, ["language"] = language, ["code"] = code };
        var clock = System.Diagnostics.Stopwatch.StartNew();
        string html = highlighter.HighlightCode(code, language);
        if (clock.Elapsed > TimeSpan.FromSeconds(1)) Console.Error.WriteLine($"slow: {name} {clock.Elapsed.TotalSeconds:F1} s");
        bool timedOut = false;
        if (Languages.FindById(language.Trim().ToLowerInvariant() is var l && l.Length > 0 ? l : "-") is { } direct && code.Length > 0)
        {
            try { new HtmlClassFormatter().GetHtmlString(code, direct); }
            catch (RegexMatchTimeoutException) { timedOut = true; }
            catch (Exception) { }
        }
        if (timedOut) entry["outcome"] = "timeout";
        else entry["html"] = NormalizeNewLines(html);
        output.Add(entry);
    }
    var result = new JsonObject
    {
        ["schemaVersion"] = "marknexia-highlight-oracle-v1",
        ["generator"] = "crates/marknexia-rendering/tests/oracle/HighlightOracle",
        ["sourceRevision"] = revision,
        ["colorCode"] = "ColorCode.Core 2.0.15, ColorCode.HTML 2.0.15",
        ["dotnet"] = dotnet,
        ["culture"] = CultureInfo.CurrentCulture.Name,
        ["context"] = "ColorCodeSyntaxHighlighter.HighlightCode(code, language); the Environment.NewLine that HtmlClassFormatter writes after <pre> and before </pre> is normalized to \\n (REND-3)",
        ["cases"] = output,
    };
    var options = new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
    File.WriteAllText(path, result.ToJsonString(options).Replace("\r\n", "\n") + "\n");
    Console.WriteLine($"wrote {output.Count} cases to {path}");
}

static string Escape(string language) => language.Length == 0 ? "(empty)" : language.Replace("\t", "\\t").Replace("\n", "\\n").Replace(" ", "_");

// HtmlClassFormatter writes Environment.NewLine after `<pre>` and before
// `</pre>`. Only those two are normalized; newlines inside the code are kept.
static string NormalizeNewLines(string html)
{
    string nl = Environment.NewLine;
    if (nl == "\n" || !html.StartsWith("<div", StringComparison.Ordinal)) return html;
    int open = html.IndexOf("<pre>" + nl, StringComparison.Ordinal);
    string close = nl + "</pre></div>";
    if (open < 0 || !html.EndsWith(close, StringComparison.Ordinal)) throw new InvalidOperationException("unexpected ColorCode wrapper");
    return html[..open] + "<pre>\n" + html[(open + 5 + nl.Length)..^close.Length] + "\n</pre></div>";
}
